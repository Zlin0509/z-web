import { test, expect } from '@playwright/test';

test('management requires login and rejects spoofed browser identity headers',async({page,request})=>{
  await page.goto('/admin/');
  await expect(page.getByRole('heading',{name:'登录，继续你的思考。'})).toBeVisible();
  expect((await request.get('/api/admin/notes')).status()).toBe(401);
  expect((await request.get('/api/admin/notes',{headers:{'oai-authenticated-user-id':'local_seedy','oai-authenticated-user-email':'seedy@sites.test'}})).status()).toBe(401);
  await page.getByRole('link',{name:'使用 ChatGPT 登录'}).click();
  await expect(page.locator('.admin-heading h1')).toContainText('笔记管理');
  await expect(page.locator('#workspace-status')).toContainText('云端已连接');
  const badOrigin=await page.request.post('/api/admin/notes',{headers:{Origin:'https://attacker.test','X-Notebook-Request':'1'},data:{document:{}}});expect(badOrigin.status()).toBe(403);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});

test('Markdown draft, preview, publish, revision, withdrawal and recycle workflow',async({page})=>{
  test.setTimeout(90000);
  const slug='browser-note-'+Date.now().toString(36)+Math.random().toString(36).slice(2,5);
  const title='在线编辑验证 '+slug;
  await page.goto('/signin-with-chatgpt?return_to=%2Fadmin%2F');
  await expect(page.locator('#workspace-status')).toContainText('云端已连接');
  await page.locator('#new-note').click();
  await page.locator('#note-title').fill(title);
  await page.locator('#note-description').fill('用于验证真实编辑发布流程');
  await page.locator('#note-slug').fill(slug);
  await page.locator('#note-body').fill('## Markdown 标题\n\n**粗体测试**\n\n```cpp\nint answer = 42;\n```');
  await page.getByRole('button',{name:'预览',exact:true}).click();
  await expect(page.locator('#markdown-preview strong')).toHaveText('粗体测试');
  const saved=page.waitForResponse(r=>r.url().includes('/api/admin/notes/')&&r.request().method()==='PUT');
  await page.locator('#save-note').click();
  const {note}=await (await saved).json();
  await expect(page.locator('#admin-alert')).toContainText('草稿已保存');
  expect((await page.request.get('/work/'+slug+'/')).status()).toBe(404);
  await page.locator('#publish-note').click();
  await expect(page.locator('#admin-alert')).toContainText('文章已发布');
  let response=await page.request.get('/work/'+slug+'/');expect(response.status()).toBe(200);expect(await response.text()).toContain('粗体测试');
  await page.getByRole('button',{name:'编辑',exact:true}).click();
  await page.locator('#note-body').fill('## 新的草稿\n只有发布后才能看到这一句。');
  await page.locator('#save-note').click();
  await expect(page.locator('#admin-alert')).toContainText('草稿已保存');
  expect(await (await page.request.get('/work/'+slug+'/')).text()).not.toContain('只有发布后才能看到这一句');
  await page.reload();
  await page.locator('.note-list-item').filter({hasText:title}).click();
  await expect(page.locator('#note-body')).toHaveValue('## 新的草稿\n只有发布后才能看到这一句。');
  await page.locator('#publish-note').click();
  await expect(page.locator('#admin-alert')).toContainText('文章已发布');
  expect(await (await page.request.get('/work/'+slug+'/')).text()).toContain('只有发布后才能看到这一句');
  await page.locator('#note-history').click();
  await expect(page.locator('#history-panel button').first()).toBeVisible();
  page.on('dialog',dialog=>dialog.accept());
  await page.locator('#unpublish-note').click();
  await expect(page.locator('#admin-alert')).toContainText('已撤回发布');
  expect((await page.request.get('/work/'+slug+'/')).status()).toBe(404);
  await page.locator('#trash-note').click();
  await expect(page.locator('#admin-alert')).toContainText('已移入回收站');
  await page.locator('#restore-note').click();
  await expect(page.locator('#admin-alert')).toContainText('已恢复为草稿');
  expect((await page.request.get('/work/'+slug+'/')).status()).toBe(404);
  const download=page.waitForEvent('download');await page.locator('#export-note').click();expect((await download).suggestedFilename()).toBe(slug+'.md');
  await page.locator('#trash-note').click();await expect(page.locator('#admin-alert')).toContainText('已移入回收站');
  expect((await (await page.request.get('/api/admin/notes/'+note.id)).json()).note.deletedAt).toBeTruthy();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
